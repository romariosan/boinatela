BEGIN;

ALTER TABLE anuncio ADD COLUMN IF NOT EXISTS uf varchar(2);
ALTER TABLE anuncio ADD COLUMN IF NOT EXISTS url_foto_principal varchar(500);
ALTER TABLE anuncio ADD COLUMN IF NOT EXISTS status_processamento varchar(30) NOT NULL DEFAULT 'PUBLICADO';

UPDATE anuncio
SET uf = upper(right(cidade, 2))
WHERE uf IS NULL AND cidade ~ ' - [A-Za-z]{2}$';

UPDATE anuncio
SET url_foto_principal = (
    SELECT f.url FROM anuncio_foto f WHERE f.anuncio_id = anuncio.id ORDER BY f.posicao ASC LIMIT 1
)
WHERE url_foto_principal IS NULL;

ALTER TABLE anuncio DROP CONSTRAINT IF EXISTS anuncio_status_processamento_check;
ALTER TABLE anuncio ADD CONSTRAINT anuncio_status_processamento_check
    CHECK (status_processamento IN ('PUBLICADO', 'RASCUNHO_SEM_FOTO'));

CREATE TABLE IF NOT EXISTS grupo_whatsapp (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    whatsapp_jid varchar(80) NOT NULL UNIQUE,
    nome_grupo varchar(160) NOT NULL,
    cidade_padrao varchar(80) NOT NULL,
    uf_padrao varchar(2) NOT NULL,
    ativo boolean NOT NULL
);

COMMIT;
